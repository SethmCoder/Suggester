export function catalogById(id: string): DestinationRecord | undefined {
  return DESTINATION_CATALOG.find((row) => row.id === id);
}

export function catalogByName(name: string): DestinationRecord | undefined {
  const needle = name.trim().toLowerCase();
  return DESTINATION_CATALOG.find(
    (row) =>
      row.name.toLowerCase() === needle ||
      row.id === needle ||
      row.name.toLowerCase().includes(needle),
  );
}
